        private IEnumerable<StatCard> StatCards
        {
            get
            {
                if (_report == null) yield break;
                yield return new StatCard(Resource.RptTotalCandidates, _report.TotalCandidates.ToString());
                yield return new StatCard(Resource.RptPass, _report.PassCount.ToString(), "color:#4CAF50;font-weight:600");
                yield return new StatCard(Resource.RptFail, _report.FailCount.ToString(), "color:#F44336;font-weight:600");
                var passColor = _report.PassRate >= 80 ? "#4CAF50" : _report.PassRate >= 50 ? "#FF9800" : "#F44336";
                yield return new StatCard(Resource.RptPassRate, $"{_report.PassRate}%", $"color:{passColor};font-weight:600");
                yield return new StatCard(Resource.RptMean, _report.Mean.ToString("F1"));
                yield return new StatCard(Resource.RptMedian, _report.Median.ToString("F1"));
                yield return new StatCard(Resource.RptMode, _report.Mode.ToString("F1"));
                yield return new StatCard(Resource.RptStdDeviation, _report.StdDev.ToString("F1"));
                yield return new StatCard(Resource.RptMinScore, _report.Min.ToString("F0"));
                yield return new StatCard(Resource.RptMaxScore, _report.Max.ToString("F0"));
                yield return new StatCard(Resource.RptSkewness, _report.Skewness.ToString("F2"), "", _report.SkewnessInterpretation);
                yield return new StatCard(Resource.RptKurtosis, _report.Kurtosis.ToString("F2"), "", _report.KurtosisInterpretation);
            }
        }

